function setProgress(S, p) {
  const {geo, N, W, H, shR, shL} = S, pos = geo.attributes.position, col = geo.attributes.color, ds = W / N;
  const theta = p * Math.PI, curl = -0.85 * Math.sin(p * Math.PI);
  let x = 0, z = 0, free = 0;
  for (let i = 0; i <= N; i++) {
    const phi = theta + curl * (i / N);
    if (i) { x += ds * Math.cos(phi); z += ds * Math.sin(phi); }
    const shade = 1 - 0.42 * (1 - Math.abs(Math.cos(phi)));
    for (let r = 0; r < 2; r++) { const k = r * (N + 1) + i; pos.setXYZ(k, x, (r ? -1 : 1) * H / 2, z); col.setXYZ(k, shade, shade, shade); }
    free = x;
  }
  pos.needsUpdate = col.needsUpdate = true; geo.computeBoundingSphere();
  const o = Math.pow(Math.sin(p * Math.PI), .8);
  const rr = Math.max(0, Math.min(W, free)), ll = Math.max(0, Math.min(W, -free));
  shR.scale.x = Math.max(rr, .001); shR.position.x = rr / 2; shR.material.opacity = free > 0 ? o : 0;
  shL.scale.x = Math.max(ll, .001); shL.position.x = -ll / 2; shL.material.opacity = free < 0 ? o : 0;
  renderer.render(S.scene, S.camera);
}
const ease = t => t < .5 ? 4 * t * t * t : 1 - Math.pow(-2 * t + 2, 3) / 2;
async function go(next) {
  next = Math.max(0, Math.min(nSpreads() - 1, next));
  if (busy || next === state.spread) return;
  if (reduce || !wide.matches || !webgl()) { state.spread = next; render(); return; }
  busy = true;
  const ok = await Promise.race([loadThree(), new Promise(r => setTimeout(() => r(false), 2000))]);
  if (!ok || !window.THREE) { state.spread = next; render(); busy = false; return; }
  let S; try { S = buildScene(Math.min(state.spread, next)); } catch (e) { state.spread = next; render(); busy = false; return; }
  const fwd = next > state.spread; spreadEl.classList.add('hidden-pages');
  const t0 = performance.now(), D_ = 1300;
  await new Promise(done => { (function step(now) { const t = Math.min(1, (now - t0) / D_), e = ease(t);
    setProgress(S, fwd ? e : 1 - e); t < 1 ? requestAnimationFrame(step) : done(); })(t0); });
  state.spread = next; render(); spreadEl.classList.remove('hidden-pages'); document.getElementById('flip').hidden = true; busy = false;
}
