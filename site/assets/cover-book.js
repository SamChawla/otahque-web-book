function pageSvg(p, i) {
  let s = `<rect width="600" height="800" fill="${p.bg}"/>`, group = null;
  const flush = () => { if (group) { s += `<a href="${esc(group.href)}">${group.html}</a>`; group = null; } };
  p.ops.forEach(o => { const h = o.href;
    if (h) { if (group && group.href === h && o.k !== 'hit') group.html += opSvg(o); else { flush(); group = {href:h, html:opSvg(o)}; } }
    else { flush(); s += opSvg(o); } });
  flush();
  return `<svg class="pg" viewBox="0 0 600 800" role="group" aria-label="${esc(p.label)}">${s}<g pointer-events="none">${gutterDef(i)}</g></svg>`;
}
